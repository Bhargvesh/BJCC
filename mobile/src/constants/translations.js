/**
 * Instantly get a UI string for the given key in the given language code.
 * Falls back to English if the key doesn't exist in the target language.
 */
export function getTranslation(langCode, key) {
  const lc = (langCode || "en").toLowerCase();
  return T[lc]?.[key] ?? T.en?.[key] ?? key;
}

/**
 * Get the entire translations object for a language code.
 * Merges with English defaults so every key is guaranteed present.
 */
export function getTranslations(langCode) {
  const lc = (langCode || "en").toLowerCase();
  if (lc === "en") return T.en;
  return { ...T.en, ...(T[lc] || {}) };
}

